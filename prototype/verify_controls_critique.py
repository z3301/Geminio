"""Re-derive the numerical claims of the 2026-10-27 independent review of controls C, D and E from the
saved per-run tables, so that the corrected write-ups rest on reproducible numbers.

Reads results/client_encoder_plain/runs.csv (arms rigged, plain, dup), results/client_encoder_swap_qair_qeff/
runs.csv (adds swap) and results/complementarity/temperature_sweep.csv. Writes
results/complementarity/validation_2026_10_27_checks.md.

Checks:
  1. medical plain-head runs with n_unique_best == 1 (review: 19 of 21, not "every")
  2. head x encoder interaction on UAV: I_e = (rigged - plain)_e - (rigged - plain)_CLIP, per seed
  3. Spearman over encoders: head selectivity effect vs plain-head target LPIPS, all 7 and robust-only
  4. distinct reconstructions used (n_unique_best) by arm on UAV
  5. plain-head encoder effect on UAV: each robust encoder vs CLIP, paired over seeds
  6. swap - plain on UAV, per encoder, for batch LPIPS, target LPIPS and n_unique_best
  7. temperature sweep: loss ratio vs selectivity within each head replicate and replicate-centred
Usage: python prototype/verify_controls_critique.py
"""
import csv
import os

import numpy as np
from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'results', 'complementarity', 'validation_2026_10_27_checks.md')
ENC = ['clip', 'simclip2', 'simclip4', 'fare2', 'fare4', 'tecoa2', 'tecoa4']
ROBUST = ENC[1:]
SEEDS = [42, 123, 256]


def read(path):
    with open(os.path.join(ROOT, path)) as f:
        return list(csv.DictReader(f))


def val(rows, domain, arm, enc, seed, key):
    for r in rows:
        if r['domain'] == domain and r['arm'] == arm and r['encoder'] == enc and int(r['seed']) == seed:
            return float(r[key])
    return float('nan')


def main():
    plain = read('results/client_encoder_plain/runs.csv')
    swap = read('results/client_encoder_swap_qair_qeff/runs.csv')
    L = ['# Checks of the 2026-10-27 review of controls C, D, E', '',
         'Generated by `prototype/verify_controls_critique.py` from the saved per-run tables.', '']

    # 1
    med = [r for r in plain if r['domain'] == 'medical' and r['arm'] == 'plain']
    n1 = sum(float(r['n_unique_best']) == 1 for r in med)
    others = [(r['encoder'], r['seed'], r['n_unique_best']) for r in med if float(r['n_unique_best']) != 1]
    L += ['## 1. Medical plain-head runs collapsed onto one reconstruction', '',
          f'{n1} of {len(med)} runs have n_unique_best = 1. Exceptions: {others}.', '']

    # 2 and 3
    L += ['## 2. Head x encoder interaction on UAV', '',
          'I_e = (rigged − plain) on encoder e minus (rigged − plain) on vanilla CLIP, same seed.', '',
          '| metric | encoder | I per seed (42 / 123 / 256) | all seeds > 0 |', '|---|---|---|---|']
    for key in ['selectivity', 'selectivity_hung']:
        npos = 0
        for e in ROBUST:
            I = []
            for s in SEEDS:
                d_e = val(plain, 'uav', 'rigged', e, s, key) - val(plain, 'uav', 'plain', e, s, key)
                d_c = val(plain, 'uav', 'rigged', 'clip', s, key) - val(plain, 'uav', 'plain', 'clip', s, key)
                I.append(d_e - d_c)
            ok = all(x > 0 for x in I); npos += ok
            L.append(f"| {key} | {e} | {' / '.join(f'{x:+.3f}' for x in I)} | {'yes' if ok else 'no'} |")
        L.append(f'| {key} | **robust encoders with I > 0 on every seed** | | **{npos}/6** |')
    for key in ['selectivity']:
        npos = 0
        for e in ROBUST:
            I = [(val(plain, 'medical', 'rigged', e, s, key) - val(plain, 'medical', 'plain', e, s, key))
                 - (val(plain, 'medical', 'rigged', 'clip', s, key) - val(plain, 'medical', 'plain', 'clip', s, key)) for s in SEEDS]
            npos += np.mean(I) > 0
        L.append(f'| medical {key} | robust encoders with mean I > 0 | | {npos}/6 |')
    L += ['', 'All contrasts share one non-robust comparator (vanilla CLIP), so the interaction is descriptive.', '']
    head_eff = {e: np.mean([val(plain, 'uav', 'rigged', e, s, 'selectivity') - val(plain, 'uav', 'plain', e, s, 'selectivity') for s in SEEDS]) for e in ENC}
    inv = {e: np.mean([val(plain, 'uav', 'plain', e, s, 'target_lpips') for s in SEEDS]) for e in ENC}
    r_all = stats.spearmanr([head_eff[e] for e in ENC], [inv[e] for e in ENC])
    r_rob = stats.spearmanr([head_eff[e] for e in ROBUST], [inv[e] for e in ROBUST])
    L += ['## 3. Does the head effect scale with backbone invertibility? (UAV)', '',
          'Head effect = rigged − plain best-match selectivity; invertibility = plain-head target LPIPS (lower = more invertible).', '',
          f'- all 7 encoders: rho = {r_all[0]:+.2f}, p = {r_all[1]:.3f}',
          f'- robust only (6): rho = {r_rob[0]:+.2f}, p = {r_rob[1]:.3f}', '']

    # 4
    L += ['## 4. Distinct reconstructions used by best-match, UAV (mean over 7 encoders x 3 seeds)', '']
    for arm, rows in [('rigged', plain), ('plain', plain), ('swap', swap)]:
        v = [float(r['n_unique_best']) for r in rows if r['domain'] == 'uav' and r['arm'] == arm]
        L.append(f'- {arm}: {np.mean(v):.2f} (n = {len(v)})')
    L.append('')

    # 5
    L += ['## 5. Plain-head encoder effect on UAV: robust encoder minus CLIP, paired over seeds', '',
          '| encoder | target LPIPS Δ (p) | Hungarian target LPIPS Δ (p) | batch LPIPS Δ (p) |', '|---|---|---|---|']
    for e in ROBUST:
        cells = []
        for key in ['target_lpips', 'target_lpips_hung', 'lpips']:
            a = [val(plain, 'uav', 'plain', e, s, key) for s in SEEDS]
            b = [val(plain, 'uav', 'plain', 'clip', s, key) for s in SEEDS]
            t = stats.ttest_rel(a, b)
            cells.append(f'{np.mean(a) - np.mean(b):+.3f} ({t.pvalue:.3f})')
        L.append(f'| {e} | ' + ' | '.join(cells) + ' |')
    L.append('')

    # 6
    L += ['## 6. Swap minus plain on UAV, per encoder (paired over seeds)', '',
          '| encoder | batch LPIPS Δ (p) | solar target LPIPS Δ (p) | n_unique plain → swap |', '|---|---|---|---|']
    for e in ENC:
        cells = []
        for key in ['lpips', 'target_lpips']:
            a = [val(swap, 'uav', 'swap', e, s, key) for s in SEEDS]
            b = [val(swap, 'uav', 'plain', e, s, key) for s in SEEDS]
            t = stats.ttest_rel(a, b)
            cells.append(f'{np.mean(a) - np.mean(b):+.3f} ({t.pvalue:.3f})')
        nu_p = np.mean([val(swap, 'uav', 'plain', e, s, 'n_unique_best') for s in SEEDS])
        nu_s = np.mean([val(swap, 'uav', 'swap', e, s, 'n_unique_best') for s in SEEDS])
        L.append(f'| {e} | ' + ' | '.join(cells) + f' | {nu_p:.2f} → {nu_s:.2f} |')
    L.append('')

    # 7
    temp = read('results/complementarity/temperature_sweep.csv')
    L += ['## 7. Temperature sweep: loss ratio vs selectivity within each head replicate (head means, duplicates excluded)', '',
          '| domain | metric | rep 1 rho | rep 2 rho | replicate-centred rho (n = 10) | p |', '|---|---|---|---|---|---|']
    for domain in ['medical', 'uav']:
        heads = {}
        for r in temp:
            if r['domain'] != domain or r['kind'] == 'dup':
                continue
            heads.setdefault((int(r['T']), int(r['rep'])), []).append(r)
        H = [dict(rep=rep, lr=float(rr[0]['loss_ratio']),
                  **{k: np.mean([float(x[k]) for x in rr]) for k in ['selectivity', 'selectivity_hung', 'target_lpips']})
             for (T, rep), rr in sorted(heads.items())]
        for key in ['selectivity', 'selectivity_hung', 'target_lpips']:
            within = [stats.spearmanr([h['lr'] for h in H if h['rep'] == rep], [h[key] for h in H if h['rep'] == rep])[0] for rep in (1, 2)]
            cx, cy = [], []
            for rep in (1, 2):
                hs = [h for h in H if h['rep'] == rep]
                mx, my = np.mean([h['lr'] for h in hs]), np.mean([h[key] for h in hs])
                cx += [h['lr'] - mx for h in hs]; cy += [h[key] - my for h in hs]
            rc = stats.spearmanr(cx, cy)
            L.append(f'| {domain} | {key} | {within[0]:+.2f} | {within[1]:+.2f} | {rc[0]:+.2f} | {rc[1]:.3f} |')
    L.append('')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
